"""Regression tests: Aviasales search links on shared trip pages.

After the Google→Aviasales swap, the boarding-pass action button on shared
trips must:
  - carry the label "Aviasales ↗"
  - point to aviasales.com/search/ (not google.com/travel/flights)
  - embed the affiliate marker (starts with 756039)

Covers both share kinds:
  - escape  → escape_card macro  (mode='share')
  - detour  → detour_card macro  (mode='share')
"""

from __future__ import annotations

from datetime import date

import pytest
from fastapi.testclient import TestClient

import yonder.encyclopedia as enc_module
import yonder.share as share_module
import yonder.vibe_signals as vs
import yonder.web as web_module
from yonder.links import AVIASALES_MARKER, aviasales_url


