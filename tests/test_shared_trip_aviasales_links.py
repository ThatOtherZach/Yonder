# ---------------------------------------------------------------------------
# Escape card — sanity: no offer url → no button rendered
# ---------------------------------------------------------------------------


class TestEscapeCardNoUrl:
    """When the offer has no google_flights_url, no Aviasales button is rendered."""

    def test_no_button_when_url_missing(self, client):
        """Omitting google_flights_url from the offer must suppress the button."""
        share = share_module.create_share(
            kind="escape",
            title="YVR → SYD",
            payload={
                "query": {
                    "origin": "YVR",
                    "destination": "SYD",
                    "depart": _DEPART,
                    "adults": 1,
                    "currency": "CAD",
                    "nonstop": False,
                },
                "offer": {
                    "price": 1200.0,
                    "currency": "CAD",
                    "price_kind": "mock",
                    # deliberately no google_flights_url
                },
                "vibe": "adventure",
            },
        )
        resp = client.get(f"/t/{share.id}")

        assert resp.status_code == 200, f"Expected 200, got {resp.status_code}"
        # When google_flights_url is absent the template skips the button entirely.
        assert "aviasales.com/search/" not in resp.text, (
            "Expected no Aviasales button when offer has no google_flights_url"
        )
